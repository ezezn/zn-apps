#!/usr/bin/env node
/**
 * generate-icons — Construye el sprite SVG de un proyecto a partir de su
 * `icon-profile.json` (scanned + manual).
 *
 * Cada proyecto publica su propio chunk de iconos, filtrado a los nombres que
 * realmente usa; nunca se copia la colección completa por accidente:
 *
 *   @zn-apps/ui-core  → shared/ui-core/dist/icons/   (solo iconos de sus componentes)
 *   kitchensink       → kitchensink/public/icons/ (+ dist/icons)  (catálogo completo,
 *                       declarado en el array `manual` de su icon-profile.json)
 *   zound-box         → zound-box/public/icons/     (vacío si no usa iconos)
 *
 * Las apps también incorporan los iconos que usan los componentes de ui-core:
 * el chunk de la app es la unión de su perfil y el de la librería.
 *
 * Se escribe en `public/icons/` para que Vite lo sirva en desarrollo y lo copie
 * a `dist/icons/` durante el build. Si `dist/` ya existe también se refresca
 * allí para dejar el chunk publicado.
 *
 * Uso:
 *   node shared/ui-core/scripts/generate-icons.mjs --profile shared
 *   node shared/ui-core/scripts/generate-icons.mjs --profile app:kitchensink
 *   node shared/ui-core/scripts/generate-icons.mjs --profile app:zound-box
 */

import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync
} from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const FAMILIES = ['filled', 'outlined', 'round', 'sharp', 'two-tone']

const scriptDir = dirname(fileURLToPath(import.meta.url))
const monorepoRoot = resolve(scriptDir, '..', '..', '..')
const iconsRoot = join(monorepoRoot, 'node_modules', '@material-design-icons', 'svg')

const SVG_TAG_RE = /<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/
const VIEWBOX_RE = /\bviewBox\s*=\s*"([^"]+)"/
const DEFAULT_VIEWBOX = '0 0 24 24'

function fail(message) {
  console.error(`\n❌ ${message}\n`)
  process.exit(1)
}

function sortNames(values) {
  return [...values].sort((a, b) => a.localeCompare(b, 'en'))
}

/** Proyecto al que pertenece un perfil. */
function resolveProject(profile) {
  if (profile === 'shared') {
    return { name: 'ui-core', dir: join(monorepoRoot, 'shared', 'ui-core'), isLibrary: true }
  }
  if (profile.startsWith('app:')) {
    const name = profile.slice(4)
    const dir = join(monorepoRoot, name)
    if (!existsSync(dir)) fail(`El perfil "${profile}" apunta a un proyecto inexistente: ${dir}`)
    return { name, dir, isLibrary: false }
  }
  fail('Perfil no reconocido. Usa --profile shared o --profile app:<nombre>.')
}

/** Lee el perfil de iconos y devuelve la unión de scanned + manual. */
function readProfileNames(projectDir, label) {
  const profileFile = join(projectDir, 'icon-profile.json')
  if (!existsSync(profileFile)) {
    fail(`Falta ${profileFile}. Ejecuta "npm run scan:icons" en ese proyecto.`)
  }

  let profile
  try {
    profile = JSON.parse(readFileSync(profileFile, 'utf8'))
  } catch {
    fail(`${profileFile} no es JSON válido.`)
  }

  const names = new Set()
  for (const key of ['scanned', 'manual']) {
    for (const value of Array.isArray(profile?.[key]) ? profile[key] : []) {
      if (typeof value === 'string' && value.trim()) names.add(value.trim())
    }
  }

  console.log(`   ${label.padEnd(9)} ${names.size} iconos (${profile?.scanned?.length ?? 0} scanned + ${profile?.manual?.length ?? 0} manual)`)
  return names
}

/** Nombres disponibles en una familia, leídos de @material-design-icons/svg. */
function readFamilyNames(family) {
  const familyDir = join(iconsRoot, family)
  if (!existsSync(familyDir)) {
    fail(`No se encontró ${familyDir}. Instala las dependencias (npm install).`)
  }
  return readdirSync(familyDir)
    .filter((file) => file.endsWith('.svg'))
    .map((file) => file.slice(0, -4))
}

/**
 * Convierte un SVG de Material Icons en un <symbol>.
 * Se conserva el viewBox original (`0 -960 960 960`), necesario para que el
 * path no quede fuera del viewport.
 */
function toSymbol(family, name, svg) {
  const match = SVG_TAG_RE.exec(svg)
  if (!match) return null

  const viewBox = VIEWBOX_RE.exec(match[1])?.[1] || DEFAULT_VIEWBOX
  const inner = match[2].trim()

  return `  <symbol id="zn-icon-${family}-${name}" viewBox="${viewBox}">${inner}</symbol>`
}

function buildSprite(family, symbols, profile, projectName) {
  return [
    `<!-- Generated by generate-icons.mjs · profile ${profile} · ${projectName} -->`,
    `<svg xmlns="http://www.w3.org/2000/svg" id="zn-icon-sprite-${family}" aria-hidden="true">`,
    ...symbols,
    '</svg>',
    ''
  ].join('\n')
}

function main() {
  const args = process.argv.slice(2)
  const profileIndex = args.indexOf('--profile')
  const profile = profileIndex >= 0 ? args[profileIndex + 1] : 'shared'

  const project = resolveProject(profile)
  const iconProfileFile = join(project.dir, 'icon-profile.json')

  console.log(`\n🎨 Sprite de iconos · ${profile}`)
  console.log(`   Proyecto: ${project.dir}`)

  const names = readProfileNames(project.dir, project.name)

  // Las apps incluyen además los iconos usados por los componentes de ui-core.
  if (!project.isLibrary) {
    const uiCoreDir = join(monorepoRoot, 'shared', 'ui-core')
    if (existsSync(join(uiCoreDir, 'icon-profile.json'))) {
      for (const name of readProfileNames(uiCoreDir, 'ui-core')) names.add(name)
    }
  }

  if (names.size === 0) {
    console.log('   El perfil no declara iconos: no se genera ningún sprite.')
    console.log(`   → ${iconProfileFile}\n`)
    return
  }

  const targets = project.isLibrary
    ? [join(project.dir, 'dist', 'icons')]
    : [
        join(project.dir, 'public', 'icons'),
        ...(existsSync(join(project.dir, 'dist')) ? [join(project.dir, 'dist', 'icons')] : [])
      ]

  const allIcons = new Set(readFamilyNames('filled'))
  const unknown = sortNames([...names].filter((name) => !allIcons.has(name)))

  let total = 0
  const generated = []

  for (const family of FAMILIES) {
    const available = new Set(readFamilyNames(family))
    const selected = sortNames([...names].filter((name) => available.has(name)))

    const symbols = []
    for (const name of selected) {
      const svg = readFileSync(join(iconsRoot, family, `${name}.svg`), 'utf8')
      const symbol = toSymbol(family, name, svg)
      if (symbol) symbols.push(symbol)
    }

    for (const targetDir of targets) {
      mkdirSync(targetDir, { recursive: true })
      const spriteFile = join(targetDir, `sprite-${family}.svg`)

      if (symbols.length === 0) {
        rmSync(spriteFile, { force: true })
        continue
      }

      writeFileSync(spriteFile, buildSprite(family, symbols, profile, project.name), 'utf8')
    }

    total += symbols.length
    generated.push(`${family} (${symbols.length})`)
  }

  console.log(`   Familias: ${generated.join(', ')}`)
  console.log(`   Total de iconos: ${total}`)
  if (unknown.length > 0) {
    console.warn(`   ⚠️  Nombres sin correspondencia en Material Icons: ${unknown.join(', ')}`)
  }
  for (const targetDir of targets) {
    console.log(`   → ${targetDir}`)
  }
  console.log()
}

main()
