import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest'

/** Mock readFamilyNames - reads from @material-design-icons/svg */
function createMockReadFamilyNames() {
  // Simulate the five Material Icon families with some icons
  const families = {
    filled: ['home', 'delete', 'play_arrow', 'settings', 'pause'],
    outlined: ['home', 'delete', 'play_arrow', 'settings', 'pause'],
    round: ['home', 'delete', 'play_arrow', 'settings', 'pause'],
    sharp: ['home', 'delete', 'play_arrow', 'settings', 'pause'],
    'two-tone': ['home', 'delete', 'play_arrow', 'settings', 'pause']
  }

  let callCount = 0
  return function mockReadFamilyNames(family) {
    callCount++
    const available = new Set(families[family] || [])
    // Return the file names (without .svg extension)
    return [...available].map((name) => `${name}.svg`)
  }
}

describe('generate-icons: family name resolution', () => {
  it('reads all five Material Icon families', () => {
    const mock = createMockReadFamilyNames()
    const FAMILIES = ['filled', 'outlined', 'round', 'sharp', 'two-tone']
    for (const family of FAMILIES) {
      const result = mock(family)
      expect(result).toBeInstanceOf(Array)
      expect(result.length).toBeGreaterThan(0)
    }
  })

  it('returns empty array for unknown family', () => {
    const mock = createMockReadFamilyNames()
    expect(mock('unknown')).toEqual([])
  })
})

describe('generate-icons: toSymbol conversion', () => {
  function toSymbol(family, name, svg) {
    const SVG_TAG_RE = /<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/
    const VIEWBOX_RE = /\bviewBox\s*=\s*"([^"]+)"/
    const DEFAULT_VIEWBOX = '0 0 24 24'

    const match = SVG_TAG_RE.exec(svg)
    if (!match) return null

    const viewBox = VIEWBOX_RE.exec(match[1])?.[1] || DEFAULT_VIEWBOX
    const inner = match[2].trim()

    return `  <symbol id="zn-icon-${family}-${name}" viewBox="${viewBox}">${inner}</symbol>`
  }

  it('extracts viewBox from SVG tag attributes', () => {
    const svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="M0 0h24v24H0z"/></svg>'
    const result = toSymbol('filled', 'home', svg)
    expect(result).toContain('viewBox="0 0 24 24"')
    expect(result).toContain('zn-icon-filled-home')
  })

  it('falls back to default viewBox when none specified', () => {
    const svg = '<svg xmlns="http://www.w3.org/2000/svg"><path d="M0 0h24v24H0z"/></svg>'
    const result = toSymbol('filled', 'home', svg)
    expect(result).toContain('viewBox="0 0 24 24"')
  })

  it('extracts symbol inner content', () => {
    const svg = '<svg a="attrib"><path d="M10 10"/></svg>'
    const result = toSymbol('filled', 'home', svg)
    expect(result).toContain('M10 10')
  })
})

describe('generate-icons: sprite building', () => {
  function buildSprite(family, symbols, profile, projectName) {
    return [
      `<!-- Generated by generate-icons.mjs · profile ${profile} · ${projectName} -->`,
      `<svg xmlns="http://www.w3.org/2000/svg" id="zn-icon-sprite-${family}" aria-hidden="true">`,
      ...symbols,
      '</svg>'
    ].join('\n')
  }

  it('builds sprite with symbols', () => {
    const symbols = [
      '  <symbol id="zn-icon-filled-home" viewBox="0 0 24 24"><path d="M0 0h24v24H0z"/></symbol>'
    ]
    const sprite = buildSprite('filled', symbols, 'test-profile', 'test-project')
    expect(sprite).toContain('zn-icon-sprite-filled')
    expect(sprite).toContain('zn-icon-filled-home')
    expect(sprite).toContain('<!-- Generated by generate-icons.mjs · profile test-profile · test-project -->')
  })

  it('builds sprite with multiple families', () => {
    const symbolsFilled = [
      '  <symbol id="zn-icon-filled-home" viewBox="0 0 24 24"><path d="M0 0h24v24H0z"/></symbol>'
    ]
    const symbolsOutlined = [
      '  <symbol id="zn-icon-outlined-home" viewBox="0 0 24 24"><path d="M0 0h24v24H0z"/></symbol>'
    ]
    const spriteFilled = buildSprite('filled', symbolsFilled, 'profile', 'app')
    const spriteOutlined = buildSprite('outlined', symbolsOutlined, 'profile', 'app')
    expect(spriteFilled).toContain('id="zn-icon-sprite-filled"')
    expect(spriteOutlined).toContain('id="zn-icon-sprite-outlined"')
  })
})

describe('generate-icons: profile names reading', () => {
  it('can read profile names from a JSON file structure', () => {
    const profile = {
      scanned: ['home', 'play_arrow'],
      manual: ['favorite', 'settings']
    }
    const names = new Set()
    for (const key of ['scanned', 'manual']) {
      for (const value of profile[key]) {
        if (typeof value === 'string' && value.trim()) names.add(value.trim())
      }
    }
    expect(names).toContain('home')
    expect(names).toContain('play_arrow')
    expect(names).toContain('favorite')
    expect(names).toContain('settings')
    expect(names.size).toBe(4)
  })

  it('handles missing profile gracefully', () => {
    const profile = {}
    const names = new Set()
    for (const key of ['scanned', 'manual']) {
      const values = profile[key] || []
      for (const value of values) {
        if (typeof value === 'string' && value.trim()) names.add(value.trim())
      }
    }
    expect(names.size).toBe(0)
  })
})

describe('generate-icons: sortNames utility', () => {
  function sortNames(values) {
    return [...values].sort((a, b) => a.localeCompare(b, 'en'))
  }

  it('sorts icon names alphabetically', () => {
    expect(sortNames(['play_arrow', 'home', 'settings'])).toEqual(['home', 'play_arrow', 'settings'])
  })

  it('sorts names with underscores correctly', () => {
    expect(sortNames(['delete', 'home', 'favorite'])).toEqual(['delete', 'favorite', 'home'])
  })
})

describe('generate-icons: main flow with names', () => {
  function readFamilyNames(family) {
    const families = {
      filled: ['home.svg', 'delete.svg', 'play_arrow.svg'],
      outlined: ['home.svg', 'delete.svg'],
      round: ['home.svg'],
      sharp: ['home.svg'],
      'two-tone': ['home.svg']
    }
    return (families[family] || [])
  }

  function mainMock() {
    const FAMILIES = ['filled', 'outlined', 'round', 'sharp', 'two-tone']
    // Names without .svg extension (as declared in icon-profile.json)
    const names = new Set(['home', 'play_arrow'])

    for (const family of FAMILIES) {
      // Available icons with .svg extension (as stored in Material Icons folder)
      const available = new Set(readFamilyNames(family))
      const selected = [...names].filter((name) => available.has(`${name}.svg`))
      expect(selected).toContain('home') // home is in all families
    }
  }

  it('home icon is selected in all families', () => {
    mainMock()
  })

  it('play_arrow is selected in filled and outlined', () => {
    // Just verify the filtering logic
    const filledAvailable = new Set(['home.svg', 'play_arrow.svg', 'settings.svg'])
    const selected = ['home', 'play_arrow'].filter((name) => filledAvailable.has(`${name}.svg`))
    expect(selected).toEqual(['home', 'play_arrow'])
  })

  it('filters out icons not in the family', () => {
    const outlinedAvailable = new Set(['home.svg', 'delete.svg'])
    const selected = ['home', 'play_arrow', 'delete'].filter((name) => outlinedAvailable.has(`${name}.svg`))
    expect(selected).toEqual(['home', 'delete'])
    expect(selected).not.toContain('play_arrow')
  })
})